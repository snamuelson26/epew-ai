/**
 * Converts a dotted key into nested JSON.
 */
function setNestedValue(
  target: Record<string, unknown>,
  dottedKey: string,
  value: string,
  preserveExisting: boolean,
): {
  created: boolean;
  preserved: boolean;
} {
  const segments = dottedKey
    .split(".")
    .map((segment) => segment.trim())
    .filter(Boolean);

  if (segments.length === 0) {
    return {
      created: false,
      preserved: false,
    };
  }

  let current = target;

  for (
    let index = 0;
    index < segments.length - 1;
    index += 1
  ) {
    const segment = segments[index];

    if (!segment) {
      continue;
    }

    const existing = current[segment];

    if (
      !existing ||
      typeof existing !== "object" ||
      Array.isArray(existing)
    ) {
      current[segment] = {};
    }

    current = current[segment] as Record<string, unknown>;
  }

  const finalSegment = segments.at(-1);

  if (!finalSegment) {
    return {
      created: false,
      preserved: false,
    };
  }

  if (
    preserveExisting &&
    current[finalSegment] !== undefined
  ) {
    return {
      created: false,
      preserved: true,
    };
  }

  const created = current[finalSegment] === undefined;

  current[finalSegment] = value;

  return {
    created,
    preserved: false,
  };
}

/**
 * Returns a nested JSON value.
 */
function getNestedValue(
  target: Record<string, unknown>,
  dottedKey: string,
): unknown {
  const segments = dottedKey
    .split(".")
    .map((segment) => segment.trim())
    .filter(Boolean);

  let current: unknown = target;

  for (const segment of segments) {
    if (
      !current ||
      typeof current !== "object" ||
      Array.isArray(current)
    ) {
      return undefined;
    }

    current = (
      current as Record<string, unknown>
    )[segment];
  }

  return current;
}

/**
 * Reads a JSON object or returns an empty object.
 */
async function readJsonObject(
  filePath: string,
): Promise<{
  data: Record<string, unknown>;
  exists: boolean;
  error: string | null;
}> {
  if (!(await pathExists(filePath))) {
    return {
      data: {},
      exists: false,
      error: null,
    };
  }

  try {
    const content = await fs.readFile(filePath, "utf8");

    const parsed =
      safeParseJson<Record<string, unknown>>(content);

    if (!parsed.success) {
      return {
        data: {},
        exists: true,
        error: parsed.error,
      };
    }

    return {
      data: parsed.data,
      exists: true,
      error: null,
    };
  } catch (error) {
    return {
      data: {},
      exists: true,
      error:
        error instanceof Error
          ? error.message
          : "Unknown JSON-reading error.",
    };
  }
}

/**
 * Writes one JSON file.
 */
async function writeJsonObject(
  filePath: string,
  value: Record<string, unknown>,
): Promise<void> {
  await ensureDirectory(path.dirname(filePath));

  await fs.writeFile(
    filePath,
    formatJson(value, 2),
    "utf8",
  );
}

